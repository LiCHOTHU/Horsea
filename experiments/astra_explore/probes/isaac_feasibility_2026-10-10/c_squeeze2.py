def squeeze2(name, wx_off=-0.08, press=0.012, z_off=0.06, lift=0.15):
    o = task.reset()
    can = np.array(task.privileged()["can_pos"])
    fR, pR, fL, pL = (1, 0, 0), (0, 1, 0), (1, 0, 0), (0, -1, 0)
    rw = can + np.array([wx_off, -0.044, z_off])
    lw = can + np.array([wx_off, +0.044, z_off])
    D(left=H((-0.09, 0.30, 1.22), f=fL, p=pL), right=H((0.10, -0.25, 1.30), f=fR, p=pR), steps=45, tag="L back-out / R reorient")
    D(left=H((-0.09, 0.02, 1.15), f=fL, p=pL), right=H(rw + [0.0, -0.04, 0.10], f=fR, p=pR), steps=40, tag="L behind door end / R above-right")
    D(left=H(lw + [-0.10, 0.04, 0.04], f=fL, p=pL), right=H(rw + [0.0, -0.04, 0.0], f=fR, p=pR), steps=40, tag="L inside door / R beside")
    o, r, pv = D(left=H(lw + [0.0, 0.03, 0.0], f=fL, p=pL), right=H(rw + [0.0, -0.03, 0.0], f=fR, p=pR), steps=30, tag="L beside")
    snap(f"{name}_beside")
    moved = float(np.linalg.norm(np.array(pv["can_pos"][:2]) - can[:2]))
    D(left=H(lw, f=fL, p=pL), right=H(rw, f=fR, p=pR), steps=20, tag="both touch")
    o, r, pv = D(left=H(lw + [0, -press, 0], f=fL, p=pL), right=H(rw + [0, press, 0], f=fR, p=pR), steps=20, tag="squeeze")
    snap(f"{name}_squeeze")
    o, r, pv = D(left=H(lw + [0, -press, lift], f=fL, p=pL), right=H(rw + [0, press, lift], f=fR, p=pR), steps=45, tag="lift")
    snap(f"{name}_lift")
    gain = pv["can_pos"][2] - can[2]
    print(f"   RESULT {name}: can moved {moved:.3f} before squeeze; z gain {gain:.3f}; quat {np.round(pv['can_quat_wxyz'], 2).tolist()}; door {np.round(pv['drawer_joint_pos'], 3).tolist()}; t={o['steps_used']}")
    return round(gain, 3)
print("SUMMARY", {"S1": squeeze2("S1")})
