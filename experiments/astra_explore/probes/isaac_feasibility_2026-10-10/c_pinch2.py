def lat_pinch(name, w_off, f=(1, 0, 0), p=(0, 0, -1), thumb=1.0, fingers=0.0, close_steps=45, lift=0.15):
    o = task.reset()
    can = np.array(task.privileged()["can_pos"])
    w = can + np.array(w_off)
    D(right=H((0.10, -0.25, 1.30), f=f, p=p), steps=45, tag="reorient high/right")
    D(right=H(w + [0.0, 0.0, 0.12], f=f, p=p), steps=35, tag="above")
    o, r, pv = D(right=H(w, f=f, p=p), steps=30, tag="descend beside")
    moved = float(np.linalg.norm(np.array(pv["can_pos"][:2]) - can[:2]))
    names = task.tip_names["right"]
    c = np.array(pv["can_pos"])
    print("    before pinch: tips rel can [dx, dy, dz]:", {n.split("_")[1]: np.round(100 * (t - (c + [0, 0, 0.06])), 1).tolist() for n, t in zip(names, task._tips("right"))})
    snap(f"{name}_beside")
    D(right=H(w, f=f, p=p, fingers=fingers, thumb=thumb), steps=close_steps, tag="pinch")
    c = np.array(task.privileged()["can_pos"])
    print("    after pinch: tips rel can [dx, dy, dz]:", {n.split("_")[1]: np.round(100 * (t - (c + [0, 0, 0.06])), 1).tolist() for n, t in zip(names, task._tips("right"))})
    snap(f"{name}_pinched")
    o, r, pv = D(right=H(w + [0, 0, lift], f=f, p=p, fingers=fingers, thumb=thumb), steps=40, tag="lift")
    snap(f"{name}_lift")
    gain = pv["can_pos"][2] - can[2]
    print(f"   RESULT {name}: moved before pinch {moved:.3f}; z gain {gain:.3f} m; quat {np.round(pv['can_quat_wxyz'], 2).tolist()}; xy {np.round(pv['can_pos'][:2], 3).tolist()}")
    return round(gain, 3)
